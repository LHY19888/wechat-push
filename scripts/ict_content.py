def get_topic(module_key, day_of_month=None):
    """根据模块和日期获取当天的主题内容"""
    import datetime
    if day_of_month is None:
        tz = datetime.timezone(datetime.timedelta(hours=8))
        day_of_month = datetime.datetime.now(tz).day

    module = MODULES[module_key]
    topics = module["topics"]
    index = (day_of_month - 1) % len(topics)
    return topics[index]


def format_message(module_key, date_str, content):
    """格式化推送消息"""
    module = MODULES[module_key]
    header = f"{module['icon']} ICT{module['name']}\n{date_str}\n"
    separator = "━" * 20 + "\n\n"
    return header + separator + content


